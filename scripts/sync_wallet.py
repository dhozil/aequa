"""Regenerate the project .env from the shared wallet directory.

The deployer and applicant keys live outside this repository in
``../wallet`` (override with ``AEQUA_WALLET_DIR`` or ``--wallet-dir``).
This script validates each key against the address recorded in the wallet
files and writes the variables that ``gltest.config.yaml`` and
``scripts/aequa.py`` expect.

    python scripts/sync_wallet.py
    python scripts/sync_wallet.py --wallet-dir D:/Genlayer-project/wallet
"""

import argparse
import json
import os
import pathlib

from eth_account import Account

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEV_ACCOUNT = "dev"
APPLICANT_ACCOUNT = "recipient"
# Third wallet, used by the adversarial integration tests as a plain outsider.
OUTSIDER_ACCOUNT = "seller"


def _wallet_dir(cli_value: str) -> pathlib.Path:
    raw = cli_value or os.environ.get("AEQUA_WALLET_DIR") or str(ROOT.parent / "wallet")
    path = pathlib.Path(raw).expanduser().resolve()
    if not path.is_dir():
        raise SystemExit(f"wallet directory not found: {path}")
    return path


def _dev_key(wallet: pathlib.Path) -> tuple[str, str]:
    env_file = wallet / ".env"
    if not env_file.is_file():
        raise SystemExit(f"missing {env_file}")
    for line in env_file.read_text(encoding="utf-8").splitlines():
        if line.strip().startswith("#") or "=" not in line:
            continue
        name, value = line.split("=", 1)
        if name.strip() == "GENLAYER_DEV_KEY":
            return value.strip().strip('"').strip("'"), "GENLAYER_DEV_KEY"
    raise SystemExit(f"GENLAYER_DEV_KEY not found in {env_file}")


def _json_key(wallet: pathlib.Path, stem: str) -> tuple[str, str]:
    path = wallet / f"{stem}.json"
    if not path.is_file():
        raise SystemExit(f"missing {path}")
    data = json.loads(path.read_text(encoding="utf-8"))
    key = (data.get("privateKey") or "").strip()
    if not key:
        raise SystemExit(f"privateKey not found in {path}")
    return key, data.get("address", "")


def _resolve(key: str, expected: str, label: str) -> str:
    address = Account.from_key(key).address
    if expected and expected.lower() != address.lower():
        raise SystemExit(
            f"{label}: key derives {address}, wallet file says {expected}"
        )
    return address


def main() -> None:
    parser = argparse.ArgumentParser(description="Sync .env from the shared wallet directory")
    parser.add_argument("--wallet-dir", default="", help="path to the wallet directory")
    parser.add_argument("--dry-run", action="store_true", help="print the plan only")
    args = parser.parse_args()

    wallet = _wallet_dir(args.wallet_dir)
    dev_key, _ = _dev_key(wallet)
    dev_address = _resolve(dev_key, (wallet / "address.txt").read_text(encoding="utf-8").strip(), DEV_ACCOUNT)

    applicant_key, applicant_expected = _json_key(wallet, APPLICANT_ACCOUNT)
    applicant_address = _resolve(applicant_key, applicant_expected, APPLICANT_ACCOUNT)

    outsider_key, outsider_expected = _json_key(wallet, OUTSIDER_ACCOUNT)
    outsider_address = _resolve(outsider_key, outsider_expected, OUTSIDER_ACCOUNT)

    lines = [
        "# Generated by scripts/sync_wallet.py. Do not commit.",
        "",
        f"# Deployer/owner account ({DEV_ACCOUNT}).",
        f"ACCOUNT_PRIVATE_KEY={dev_key}",
        f"ACCOUNT_ADDRESS={dev_address}",
        "",
        f"# Applicant account ({APPLICANT_ACCOUNT}).",
        f"APPLICANT_PRIVATE_KEY={applicant_key}",
        f"APPLICANT_ADDRESS={applicant_address}",
        "",
        f"# Third-party account ({OUTSIDER_ACCOUNT}), used by the adversarial tests.",
        f"OUTSIDER_PRIVATE_KEY={outsider_key}",
        f"OUTSIDER_ADDRESS={outsider_address}",
        "",
    ]
    target = ROOT / ".env"
    if args.dry_run:
        print(f"wallet: {wallet}")
        print(f"owner: {dev_address}")
        print(f"applicant: {applicant_address}")
        print(f"outsider: {outsider_address}")
        print(f"would write: {target}")
        return

    target.write_text("\n".join(lines), encoding="utf-8")
    print(f"wallet: {wallet}")
    print(f"owner: {dev_address}")
    print(f"applicant: {applicant_address}")
    print(f"outsider: {outsider_address}")
    print(f"wrote: {target}")


if __name__ == "__main__":
    main()
